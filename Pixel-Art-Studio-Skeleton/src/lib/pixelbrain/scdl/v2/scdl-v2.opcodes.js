export function getSCDLV2Opcode(mnemonic) {
  return OPCODE_BY_MNEMONIC.get(mnemonic) || null;
}

export function listSCDLV2Opcodes() {
  return OPCODES;
}

export function listSCDLV2Capabilities() {
  const capMap = new Map();
  for (const op of OPCODES) {
    const capId = op.capability || 'CORE.MATH@2.0';
    if (!capMap.has(capId)) {
      capMap.set(capId, {
        id: capId,
        version: '2.0.0',
        opcodes: [],
        supportedCount: 0,
        stubbedCount: 0,
      });
    }
    const cap = capMap.get(capId);
    cap.opcodes.push(op.mnemonic);
    if (op.status === 'IMPLEMENTED' || op.status === 'SUPPORTED') cap.supportedCount += 1;
    else cap.stubbedCount += 1;
  }

  return Object.freeze({
    contract: 'PB-SCDL-CAPABILITIES-v1',
    opcodes: OPCODES,
    descriptors: Object.freeze(['PACKET', 'ASSET', 'ANY', 'SOIL_SURFACE_DESCRIPTOR']),
    formats: Object.freeze(['json', 'svg', 'phaser', 'png', 'aseprite']),
    flags: Object.freeze({ SCDL_V2_ENABLED: true }),
    capabilities: Object.freeze(Array.from(capMap.values()).map((c) => Object.freeze({
      ...c,
      opcodes: Object.freeze([...c.opcodes]),
    }))),
    rasterPolicies: Object.freeze([
      Object.freeze({ name: 'CENTER', status: 'SUPPORTED' }),
      Object.freeze({ name: 'MIDPOINT', status: 'SUPPORTED' }),
      Object.freeze({ name: 'BRESENHAM', status: 'SUPPORTED' }),
      Object.freeze({ name: 'SUPERCOVER', status: 'SUPPORTED' }),
      Object.freeze({ name: 'THRESHOLD', status: 'STUBBED', reason: "Raster policy 'THRESHOLD' is reserved but has no registered rasterizer algorithm" }),
    ]),
    compositeModes: Object.freeze([
      Object.freeze({ name: 'OVER', status: 'SUPPORTED' }),
      Object.freeze({ name: 'ADD', status: 'SUPPORTED' }),
      Object.freeze({ name: 'SUBTRACT', status: 'SUPPORTED' }),
      Object.freeze({ name: 'MULTIPLY', status: 'SUPPORTED' }),
      Object.freeze({ name: 'MASK_IN', status: 'SUPPORTED' }),
      Object.freeze({ name: 'MASK_OUT', status: 'SUPPORTED' }),
      Object.freeze({ name: 'REPLACE', status: 'SUPPORTED' }),
    ]),
  });
}
