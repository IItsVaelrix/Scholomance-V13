const OPCODES = Object.freeze(DEFINITIONS.map(([id, mnemonic, scope, operands, result, purity]) => {
  const frozenOperands = Object.freeze(operands.map(([name, type, required]) => Object.freeze({
    name,
    type,
    required,
  })));
  const isStubbed = STUBBED_COLLECTION_OPCODES.has(mnemonic);
  const isRaster = RASTER_AFFECTING_OPCODES.has(mnemonic);
  const restrictions = OPERAND_RESTRICTIONS[mnemonic] || Object.freeze({});

  return Object.freeze({
    id,
    mnemonic,
    scope: Object.freeze([...scope]),
    legalScopes: Object.freeze([...scope]),
    operands: frozenOperands,
    operandRestrictions: restrictions,
    result,
    purity,
    cost: 1,
    capability: CAPABILITIES[mnemonic],
    version: '2.0.0',
    docs: DOCS[mnemonic],
    status: isStubbed ? 'STUBBED' : (mnemonic === 'THRESHOLD' ? 'STUBBED' : 'IMPLEMENTED'),
    implemented: !isStubbed && mnemonic !== 'THRESHOLD',
    parsed: true,
    analyzed: !isStubbed,
    lowered: !isStubbed,
    evaluated: !isStubbed,
    rasterized: !isStubbed && isRaster,
    exported: !isStubbed,
    tested: !isStubbed,
  });
}));

