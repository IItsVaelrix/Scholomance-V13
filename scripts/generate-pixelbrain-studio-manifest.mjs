#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildEffectCatalog } from './pixelbrain-effect-catalog.mjs';
import { buildStudioAmpManifest } from '../codex/core/pixelbrain/studio/studio-amp-manifest.schema.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'codex/core/pixelbrain/studio/studio-amp-manifest.generated.js');

export function renderStudioManifest(records) {
  return `// Generated by scripts/generate-pixelbrain-studio-manifest.mjs. Do not edit.\n` +
    `export const STUDIO_AMP_RECORDS = Object.freeze(${JSON.stringify(records, null, 2)});\n`;
}

export async function runStudioManifestCli(argv = process.argv.slice(2)) {
  const { amps } = await buildEffectCatalog();
  const records = buildStudioAmpManifest(amps);
  const source = renderStudioManifest(records);
  if (argv.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== source) {
      console.error(`[studio-manifest] ${relative(ROOT, OUT)} is stale or missing`);
      return 1;
    }
    console.log(`[studio-manifest] current (${records.length} capabilities)`);
    return 0;
  }
  writeFileSync(OUT, source, 'utf8');
  console.log(`[studio-manifest] wrote ${relative(ROOT, OUT)} (${records.length} capabilities)`);
  return 0;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) process.exitCode = await runStudioManifestCli();
